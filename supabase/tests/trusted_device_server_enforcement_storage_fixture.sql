-- CI-only stand-in for Supabase Storage so trusted-device migration and its
-- restrictive Storage policy can be exercised in the hosted Postgres service.
-- The live Supabase project already supplies storage.objects and its existing policies.
create schema if not exists storage;

create table if not exists storage.objects (
    id bigint generated by default as identity primary key,
    bucket_id text not null,
    name text not null,
    owner_id text
);

alter table storage.objects enable row level security;
grant usage on schema storage to authenticated;
grant select, insert on storage.objects to authenticated;

drop policy if exists beekeep_ci_photo_read on storage.objects;
create policy beekeep_ci_photo_read on storage.objects
    for select to authenticated
    using (bucket_id = 'inspection-photos' and owner_id = auth.uid()::text);

drop policy if exists beekeep_ci_photo_upload on storage.objects;
create policy beekeep_ci_photo_upload on storage.objects
    for insert to authenticated
    with check (bucket_id = 'inspection-photos' and owner_id = auth.uid());
